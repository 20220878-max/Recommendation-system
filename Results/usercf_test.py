import pandas as pd
from surprise import Dataset, Reader, KNNBasic
from surprise.accuracy import rmse

# train 데이터
train = pd.read_csv(
    'ml-100k/ua.base',
    sep='\t',
    names=['user_id', 'item_id', 'rating', 'timestamp']
)

# test 데이터
test = pd.read_csv(
    'ml-100k/ua.test',
    sep='\t',
    names=['user_id', 'item_id', 'rating', 'timestamp']
)

reader = Reader(rating_scale=(1, 5))

data = Dataset.load_from_df(
    train[['user_id', 'item_id', 'rating']],
    reader
)

trainset = data.build_full_trainset()

testset = list(
    zip(
        test['user_id'],
        test['item_id'],
        test['rating']
    )
)

model = KNNBasic(
    k=50,
    sim_options={
        'name': 'cosine',
        'user_based': True
    }
)

model.fit(trainset)

predictions = model.test(testset)

rmse(predictions)

print("UserCF Test 완료")